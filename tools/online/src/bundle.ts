/**
 * Bundles the engine and the content into one file per pair of versions, for the Edge Functions.
 *
 * Deno wants import paths the packages do not use, so a function cannot import them as they
 * are. A bundle is named by the versions inside it and is never rewritten once those versions
 * have shipped: a game finishes on the versions it started with, so old bundles stay beside the
 * new one for as long as games on them are still being played.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CONTENT_VERSION } from '@ratrace/content';
import { ENGINE_VERSION } from '@ratrace/engine';
import { build } from 'esbuild';

export const GAME_DIR = fileURLToPath(new URL('../../../supabase/functions/_shared/game/', import.meta.url));

/** The file a pair of versions is bundled into. */
export const bundleName = (engine: string, content: string): string => `v${engine}-${content}.js`;

/** Builds the bundle of the versions in this checkout, without writing it. */
export async function bundleGame(): Promise<{ name: string; code: string }> {
  const result = await build({
    entryPoints: [fileURLToPath(new URL('./entry.ts', import.meta.url))],
    // The bundle names the files it was made from, relative to this folder: always the root of the repository, wherever the command is run from.
    absWorkingDir: fileURLToPath(new URL('../../../', import.meta.url)),
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    write: false,
    legalComments: 'none',
    banner: { js: `// The Rat Race, engine ${ENGINE_VERSION}, content ${CONTENT_VERSION}. Generated by \`pnpm online:bundle\`: do not edit.` },
  });
  return { name: bundleName(ENGINE_VERSION, CONTENT_VERSION), code: result.outputFiles[0].text };
}

/** The module that lists every bundle in the folder under the versions it holds. */
export function registrySource(files: readonly string[]): string {
  const bundles = [...files].filter((file) => /^v[\w.]+-[\w.]+\.js$/.test(file)).sort();
  const key = (file: string) => file.slice(1, -3).replace('-', '/');
  return [
    '// Generated by `pnpm online:bundle`: do not edit. One line for each pair of versions the server can still play.',
    "import type { GameModule } from './types.ts';",
    ...bundles.map((file, i) => `import * as g${i} from './${file}';`),
    '',
    '/** Every engine and content pair the server can play, under "engine/content". */',
    'export const GAMES: Readonly<Record<string, GameModule>> = {',
    ...bundles.map((file, i) => `  '${key(file)}': g${i} as unknown as GameModule,`),
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { name, code } = await bundleGame();
  writeFileSync(join(GAME_DIR, name), code);
  writeFileSync(join(GAME_DIR, 'index.ts'), registrySource(readdirSync(GAME_DIR)));
  console.log(`bundled ${name} (${Math.round(code.length / 1024)} KB)`);
}
