import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CONTENT_VERSION } from '@ratrace/content';
import { ENGINE_VERSION } from '@ratrace/engine';
import sharp from 'sharp';

const app = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = join(app, 'public');
const icon = join(publicDir, 'sprites/brand/brand.app_icon.png');
const iconDir = join(publicDir, 'icons');

const filesBelow = (directory: string): string[] => {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? filesBelow(path) : [path];
  });
};

const webPath = (path: string, below: string, prefix = '') => `${prefix}/${relative(below, path).split('\\').join('/')}`;

export function serviceWorker(version: string, assets: string[]) {
  return `/* Generated by scripts/pwa.ts. Do not edit. */
'use strict';

const CACHE_PREFIX = 'ratrace-';
const CACHE = CACHE_PREFIX + ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify([...new Set(assets)].sort(), null, 2)};

const cacheable = (response) => {
  if (!response || !response.ok) return false;
  const policy = response.headers.get('cache-control') || '';
  return !/no-store|private/i.test(policy);
};

const remember = async (request, response) => {
  if (cacheable(response)) {
    const cache = await caches.open(CACHE);
    await cache.put(request, response.clone());
  }
  return response;
};

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // A missing cosmetic asset should not make the whole app impossible to install.
    for (let at = 0; at < PRECACHE.length; at += 16) {
      // Locale pages set a preference cookie during normal navigation. Preloading every locale must
      // neither send account cookies nor silently change that preference to whichever page runs last.
      await Promise.all(PRECACHE.slice(at, at + 16).map((url) => cache.add(new Request(url, { cache: 'reload', credentials: 'omit' })).catch(() => undefined)));
    }
  })());
});

// The weekly notice: shown as the server sends it, and a tap opens the page it leads to, in a
// window of the game that is already open if there is one.
self.addEventListener('push', (event) => {
  let notice = {};
  try {
    notice = event.data ? event.data.json() : {};
  } catch {
    notice = {};
  }
  if (!notice.title) return;
  event.waitUntil((async () => {
    // A notice is for someone who is away: with the game open in front of them, it says nothing the screen does not.
    const open = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    if (open.some((client) => client.visibilityState === 'visible')) return;
    // One of each kind is enough: an older one still in the tray goes before the new one comes.
    if (notice.tag) for (const old of await self.registration.getNotifications({ tag: notice.tag })) old.close();
    await self.registration.showNotification(notice.title, {
      body: notice.body,
      tag: notice.tag,
      icon: '/icons/icon-192.png',
      badge: '/icons/icon-192.png',
      data: { url: notice.url || '/' },
    });
  })());
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const url = new URL((event.notification.data && event.notification.data.url) || '/', self.location.origin).href;
  event.waitUntil((async () => {
    const open = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    for (const client of open) {
      if (new URL(client.url).origin === self.location.origin && 'focus' in client) {
        await client.focus();
        if ('navigate' in client) await client.navigate(url);
        return;
      }
    }
    await self.clients.openWindow(url);
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE).map((name) => caches.delete(name)));
    if (self.registration.navigationPreload) await self.registration.navigationPreload.enable();
    await self.clients.claim();
  })());
});

const cachedFirst = async (request) => {
  const cached = await caches.match(request);
  if (cached) return cached;
  return remember(request, await fetch(request));
};

const freshFirst = async (request, event, navigation = false) => {
  try {
    const response = (navigation && await event.preloadResponse) || await fetch(request);
    return remember(request, response);
  } catch {
    const cached = await caches.match(request);
    if (cached) return cached;
    if (!navigation) throw new Error('offline');

    const url = new URL(request.url);
    if (url.pathname === '/') {
      const language = (self.navigator.language || 'en').slice(0, 2);
      const home = ['en', 'es', 'ru'].includes(language) ? '/' + language : '/en';
      const localized = await caches.match(home);
      if (localized) return localized;
    }
    return (await caches.match('/offline.html')) || Response.error();
  }
};

const refreshed = async (request, event) => {
  const cached = await caches.match(request);
  const network = fetch(request).then((response) => remember(request, response)).catch(() => undefined);
  event.waitUntil(network);
  if (cached) return cached;
  return (await network) || Response.error();
};

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;

  if (request.mode === 'navigate') {
    // OAuth and other one-time query strings must never be written to an offline cache.
    if (url.search) return;
    event.respondWith(freshFirst(request, event, true));
    return;
  }
  if (url.searchParams.has('_rsc')) {
    event.respondWith(freshFirst(request, event));
    return;
  }
  if (url.pathname.startsWith('/_next/static/') || url.pathname.startsWith('/sprites/') || url.pathname.startsWith('/icons/')) {
    event.respondWith(cachedFirst(request));
    return;
  }
  if (url.pathname === '/manifest.webmanifest' || url.pathname === '/offline.html') {
    event.respondWith(refreshed(request, event));
  }
});
`;
}

async function writeIcons() {
  mkdirSync(iconDir, { recursive: true });
  const ordinary = async (size: number, name: string) =>
    sharp(icon).resize(size, size, { kernel: sharp.kernel.nearest }).png({ compressionLevel: 9, palette: true }).toFile(join(iconDir, name));
  await Promise.all([
    ordinary(192, 'icon-192.png'),
    ordinary(512, 'icon-512.png'),
    sharp(icon)
      .resize(384, 384, { kernel: sharp.kernel.nearest })
      .extend({ top: 64, bottom: 64, left: 64, right: 64, background: '#141b33' })
      .png({ compressionLevel: 9, palette: true })
      .toFile(join(iconDir, 'icon-maskable-512.png')),
    sharp(icon).resize(180, 180, { kernel: sharp.kernel.nearest }).flatten({ background: '#141b33' }).png({ compressionLevel: 9, palette: true }).toFile(join(iconDir, 'apple-touch-icon.png')),
    // Browsers still probe this conventional URL after client-side navigations. PNG data is valid
    // for a modern favicon even when the conventional filename ends in `.ico`.
    sharp(icon).resize(32, 32, { kernel: sharp.kernel.nearest }).png({ compressionLevel: 9, palette: true }).toFile(join(publicDir, 'favicon.ico')),
  ]);
}

/** The picture a link to the game shows when it is shared, the size every network asks for. */
export const SHARE_IMAGE = { width: 1200, height: 630 } as const;

/**
 * The picture of a shared link, drawn from the game's own pixels at whole multiples so not one of them
 * blurs: a night sky with a few stars, two skylines along the bottom, the rat in its wheel on the left
 * and the name on the right. It holds no words of any language, so one picture serves them all.
 */
async function writeShareImage() {
  const { width, height } = SHARE_IMAGE;
  const sprite = (path: string, scale: number) =>
    sharp(join(publicDir, 'sprites', path))
      .metadata()
      .then(({ width: w = 0, height: h = 0 }) => sharp(join(publicDir, 'sprites', path)).resize(w * scale, h * scale, { kernel: sharp.kernel.nearest }).png().toBuffer());
  // Stars at fixed places, two pixels square, in the two creams of the game.
  const stars = [
    [120, 60], [260, 140], [420, 40], [560, 110], [700, 60], [820, 150], [960, 50], [1100, 120], [1160, 30], [60, 200], [340, 230], [1040, 220],
  ].map(([x, y], i) => ({ input: { create: { width: 4, height: 4, channels: 4 as const, background: i % 2 ? '#f4f1e4' : '#ffe9a8' } }, left: x, top: y }));
  const [left, right, wheel, name] = await Promise.all([
    sprite('skylines/skyline.new_york.png', 2),
    sprite('skylines/skyline.madrid.png', 2),
    sprite('brand/brand.mascot.png', 2),
    sprite('brand/brand.wordmark.png', 2),
  ]);
  await sharp({ create: { width, height, channels: 4, background: '#141b33' } })
    .composite([
      ...stars,
      { input: left, left: 0, top: height - 132 },
      { input: right, left: 600, top: height - 132 },
      { input: wheel, left: 40, top: 20 },
      { input: name, left: 640, top: 40 },
    ])
    .png({ compressionLevel: 9 })
    .toFile(join(publicDir, 'og.png'));
}

async function main() {
  await writeIcons();
  await writeShareImage();
  const publicFiles = filesBelow(publicDir).filter((path) => !path.endsWith('/sw.js'));
  const publicAssets = publicFiles.map((path) => webPath(path, publicDir));
  const pages = ['', '/challenge', '/collection', '/new', '/play', '/rankings', '/records'];
  const routes = [...['en', 'es', 'ru'].flatMap((locale) => pages.map((page) => `/${locale}${page}`)), '/manifest.webmanifest'];
  const built = process.argv.includes('--build');
  const nextStatic = built ? filesBelow(join(app, '.next/static')).map((path) => webPath(path, join(app, '.next/static'), '/_next/static')) : [];
  const assets = [...routes, ...publicAssets, ...nextStatic];
  // What the files hold, not only their names: a sprite drawn again under the same name is served
  // first from the cache, and only a new cache lets the player see the new drawing.
  const hash = createHash('sha256').update(`${ENGINE_VERSION}/${CONTENT_VERSION}\n${assets.sort().join('\n')}`);
  for (const path of publicFiles.sort()) hash.update(readFileSync(path));
  const fingerprint = hash.digest('hex').slice(0, 12);
  writeFileSync(join(publicDir, 'sw.js'), serviceWorker(`${ENGINE_VERSION}-${CONTENT_VERSION}-${fingerprint}`, assets));
  console.log(`pwa: ${assets.length} files, cache ${fingerprint}`);
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) await main();
