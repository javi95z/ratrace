import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CONTENT_VERSION } from '@ratrace/content';
import { ENGINE_VERSION } from '@ratrace/engine';
import { LOCALES } from '@ratrace/i18n/locales';
import { PAGES } from '../src/game/pageList';

/**
 * The site's service worker, `/sw.js`, written into the web export after `expo export` and the site's pieces (`pnpm --filter @ratrace/mobile
 * site:worker <export folder>`): the Next web's own (`apps/web/scripts/pwa.ts`), with its cache names, its language's cache and key, its offline
 * page and its rules, so that a player whose installed web app runs the Next web's worker is handed this one as an update of it. Its activate
 * deletes the Next web's versioned cache (another `ratrace-*`) and keeps the language the player last played in (`rat-race-language`).
 *
 * What differs is the export's layout: its static chunks are under `/_expo/static/` (the Next web's `/_next/static/`), the files they name
 * (typefaces, sounds, pictures) under `/assets/` with their hash in their names, and its pages are `en/index.html`, `es/play.html`, asked for as
 * `/en`, `/es/play`. Every page in every language is precached with every file the export serves (the language chunks, sprites, icons and older
 * rules among them), as the Next web precaches its pages, `public/*` and its static chunks. And the older rules a life begun under them finishes
 * under are served from the cache first: precached, they are the same file for good (`shipped.json` locks them), and a life in progress opened
 * offline needs its own.
 */
const here = dirname(fileURLToPath(import.meta.url));
/** The page the worker answers with offline where it kept nothing: the Next web's, carried by the app (`public/` is copied into the export). */
const OFFLINE_PAGE = join(here, '../public/offline.html');

/** The worker's head: its caches and what it precaches. Every part after it is written over these names. */
const head = (version: string, assets: readonly string[]) => `/* Generated by scripts/serviceWorker.ts. Do not edit. */
'use strict';

const CACHE_PREFIX = 'ratrace-';
const CACHE = CACHE_PREFIX + ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify([...new Set(assets)].sort(), null, 2)};
`;

/** What may be kept, and keeping it. */
const KEEPING = String.raw`
const cacheable = (response) => {
  if (!response || !response.ok) return false;
  const policy = response.headers.get('cache-control') || '';
  return !/no-store|private/i.test(policy);
};

const remember = async (request, response) => {
  if (cacheable(response)) {
    const cache = await caches.open(CACHE);
    await cache.put(request, response.clone());
  }
  return response;
};
`;

/** Installing: everything precached, sixteen at a time, a file that fails left out. */
const INSTALL = String.raw`
self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // A missing cosmetic asset should not make the whole app impossible to install.
    for (let at = 0; at < PRECACHE.length; at += 16) {
      // Pages are fetched with no cookies: preloading every language must neither send an account's cookies nor change the player's language.
      await Promise.all(PRECACHE.slice(at, at + 16).map((url) => cache.add(new Request(url, { cache: 'reload', credentials: 'omit' })).catch(() => undefined)));
    }
  })());
});
`;

/** Activating: the other versions' caches gone (the Next web's among them), the language kept, and the pages already open taken over. */
const ACTIVATE = String.raw`
self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE).map((name) => caches.delete(name)));
    if (self.registration.navigationPreload) await self.registration.navigationPreload.enable();
    await self.clients.claim();
  })());
});
`;

/** Answering: what is asked of the site, by its kind. */
const FETCH = String.raw`
const cachedFirst = async (request) => {
  const cached = await caches.match(request);
  if (cached) return cached;
  return remember(request, await fetch(request));
};

// The language of the last page the player opened, kept apart from the versioned cache so that a
// new version does not forget it: opened offline, the bare address goes back to it.
const LANGUAGE_CACHE = 'rat-race-language';
const LANGUAGE_KEY = '/__language';
const keepLanguage = async (address) => {
  const found = new URL(address).pathname.match(/^\/(en|es|ru)(?:\/|$)/);
  if (!found) return;
  const cache = await caches.open(LANGUAGE_CACHE);
  await cache.put(LANGUAGE_KEY, new Response(found[1]));
};
const lastLanguage = async () => {
  const kept = await caches.match(LANGUAGE_KEY, { cacheName: LANGUAGE_CACHE });
  return kept ? kept.text() : null;
};

const freshFirst = async (request, event, navigation = false) => {
  try {
    const response = (navigation && await event.preloadResponse) || await fetch(request);
    if (navigation && response.ok) event.waitUntil(keepLanguage(response.url || request.url).catch(() => undefined));
    return remember(request, response);
  } catch {
    const cached = await caches.match(request);
    if (cached) return cached;
    if (!navigation) throw new Error('offline');

    const url = new URL(request.url);
    if (url.pathname === '/') {
      const language = (await lastLanguage().catch(() => null)) || (self.navigator.language || 'en').slice(0, 2);
      const home = ['en', 'es', 'ru'].includes(language) ? '/' + language : '/en';
      const localized = await caches.match(home);
      if (localized) return localized;
    }
    return (await caches.match('/offline.html')) || Response.error();
  }
};

const refreshed = async (request, event) => {
  const cached = await caches.match(request);
  const network = fetch(request).then((response) => remember(request, response)).catch(() => undefined);
  event.waitUntil(network);
  if (cached) return cached;
  return (await network) || Response.error();
};

// Files that never change under their name: the export's chunks and the files they name (their hash in their names), the sprites and icons
// (a new drawing is a new cache), and the older rules (locked once shipped).
const UNCHANGING = ['/_expo/static/', '/assets/', '/sprites/', '/icons/', '/rules/'];

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;

  if (request.mode === 'navigate') {
    // OAuth and other one-time query strings must never be written to an offline cache.
    if (url.search) return;
    event.respondWith(freshFirst(request, event, true));
    return;
  }
  if (UNCHANGING.some((prefix) => url.pathname.startsWith(prefix))) {
    event.respondWith(cachedFirst(request));
    return;
  }
  if (url.pathname === '/manifest.webmanifest' || url.pathname === '/offline.html') {
    event.respondWith(refreshed(request, event));
  }
});
`;

/**
 * The notices: the Next web's own handlers, word for word (the tests hold them to its worker). The push service delivers what the server sends
 * (`supabase/functions/_shared/notice.ts`: `{title, body, url, tag}`, the url a page of the site such as `/es/room?code=`) to every browser that
 * turned the notices on in the Next web: its subscription is the registration's, and stays when this worker takes the place of that one.
 */
export const NOTICES = String.raw`
// The weekly notice: shown as the server sends it, and a tap opens the page it leads to, in a
// window of the game that is already open if there is one.
self.addEventListener('push', (event) => {
  let notice = {};
  try {
    notice = event.data ? event.data.json() : {};
  } catch {
    notice = {};
  }
  if (!notice.title) return;
  event.waitUntil((async () => {
    // A notice is for someone who is away: with the game open in front of them, it says nothing the screen does not.
    const open = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    if (open.some((client) => client.visibilityState === 'visible')) return;
    // One of each kind is enough: an older one still in the tray goes before the new one comes.
    if (notice.tag) for (const old of await self.registration.getNotifications({ tag: notice.tag })) old.close();
    await self.registration.showNotification(notice.title, {
      body: notice.body,
      tag: notice.tag,
      icon: '/icons/icon-192.png',
      badge: '/icons/icon-192.png',
      data: { url: notice.url || '/' },
    });
  })());
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const url = new URL((event.notification.data && event.notification.data.url) || '/', self.location.origin).href;
  event.waitUntil((async () => {
    const open = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    for (const client of open) {
      if (new URL(client.url).origin === self.location.origin && 'focus' in client) {
        await client.focus();
        if ('navigate' in client) await client.navigate(url);
        return;
      }
    }
    await self.clients.openWindow(url);
  })());
});
`;

/**
 * The worker's parts after its head, in order, each a script of its own over the head's names.
 */
export const WORKER_PARTS: readonly string[] = [KEEPING, INSTALL, NOTICES, ACTIVATE, FETCH];

/** The worker's script for the cache `ratrace-<version>`, precaching `assets` (addresses of the site), made of `parts`. */
export function serviceWorker(version: string, assets: readonly string[], parts: readonly string[] = WORKER_PARTS): string {
  return [head(version, assets), ...parts].join('');
}

/** The address after the language of a page, as the site writes it: the front door is the bare language. */
const pathOf = (page: string) => (page === '' ? '' : `/${page}`);

/** Every page of the game in every language, by its address (`/en`, `/es/play`), and the manifest, which the Next web precaches as a route. */
export const PAGE_ADDRESSES: readonly string[] = [...LOCALES.flatMap((locale) => PAGES.map((page) => `/${locale}${pathOf(page)}`)), '/manifest.webmanifest'];

/** What is in the export and is not precached as a file: what the host serves for search engines, the worker itself. */
const NOT_KEPT = new Set(['sw.js', 'sitemap.xml', 'robots.txt']);

/**
 * What the worker precaches of an export holding `files` (by their path from its folder, `/`-separated): every page in every language by its
 * address, and every file but its HTML (a page is kept by its address; the others are the router's templates and development's routes), the
 * offline page excepted, its source maps, its hidden files (`_expo/.routes.json`) and `NOT_KEPT`.
 */
export function precacheOf(files: readonly string[]): string[] {
  const kept = files.filter((path) => {
    const name = path.slice(path.lastIndexOf('/') + 1);
    if (NOT_KEPT.has(path) || name.startsWith('.') || path.endsWith('.map')) return false;
    return !path.endsWith('.html') || path === 'offline.html';
  });
  return [...new Set([...PAGE_ADDRESSES, ...kept.map((path) => `/${path}`)])];
}

/**
 * The cache's version: the rules' and the content's, and a fingerprint of the addresses precached and of what each one holds (`contentOf`, the
 * bytes the site answers it with), so that a sprite drawn again under the same name is a new cache, as the Next web's `scripts/pwa.ts` makes it.
 */
export function cacheVersion(assets: readonly string[], contentOf: (asset: string) => Buffer): string {
  const sorted = [...new Set(assets)].sort();
  const hash = createHash('sha256').update(`${ENGINE_VERSION}/${CONTENT_VERSION}\n${sorted.join('\n')}`);
  for (const asset of sorted) hash.update(contentOf(asset));
  return `${ENGINE_VERSION}-${CONTENT_VERSION}-${hash.digest('hex').slice(0, 12)}`;
}

/** The export's file an address precached is answered with: a page's own HTML (`/en` is `en/index.html`, `/es/play` is `es/play.html`), else the file. */
function fileOf(asset: string): string {
  if (asset === '/manifest.webmanifest' || !PAGE_ADDRESSES.includes(asset)) return asset.slice(1);
  return /^\/[a-z]{2}$/.test(asset) ? `${asset.slice(1)}/index.html` : `${asset.slice(1)}.html`;
}

/** Every file under `dir`, by its path from `dir`, `/`-separated. */
function filesBelow(dir: string, base = dir): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? filesBelow(path, base) : [relative(base, path).split('\\').join('/')];
  });
}

/**
 * Writes the offline page and `sw.js` into the export at `out`, and gives back what the worker precaches and its cache's version. An export that
 * lacks one of the game's pages is refused: the worker would promise it offline and keep nothing.
 */
export function writeServiceWorker(out: string): { version: string; assets: string[] } {
  copyFileSync(OFFLINE_PAGE, join(out, 'offline.html'));
  const assets = precacheOf(filesBelow(out));
  const contentOf = (asset: string) => {
    const file = fileOf(asset);
    if (!existsSync(join(out, file))) throw new Error(`the export has no ${file} (${asset}) for the worker to keep`);
    return readFileSync(join(out, file));
  };
  const version = cacheVersion(assets, contentOf);
  writeFileSync(join(out, 'sw.js'), serviceWorker(version, assets));
  return { version, assets };
}

function main() {
  const out = resolve(process.argv[2] ?? join(here, '../dist'));
  const { version, assets } = writeServiceWorker(out);
  console.log(`service worker: ${assets.length} files precached, cache ratrace-${version}, in ${out}`);
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) main();
